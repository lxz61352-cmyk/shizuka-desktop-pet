    '判定标准：这条信息一个月后是否仍然成立、以后对话里用得上；拿不准就不收。\n'
    '每条给四个字段：source_id（用户消息 id）；quote（该消息里连续的原话片段，用于溯源，必须一字不差）；'
    'fact（改写后的中文事实：第三人称用「用户」，不超过 40 字，不依赖上下文，不带引号、换行或语气词；'
